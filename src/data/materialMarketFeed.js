const buildHistory = (price, benchmark = price) => {
  const baseline = Math.max(Math.round(price * 0.94), 1);
  const mid = Math.max(Math.round((baseline + benchmark) / 2), 1);
  return Array.from(new Set([baseline, mid, benchmark, price].filter((value) => value > 0)));
};

